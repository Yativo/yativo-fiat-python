#!/usr/bin/env python3
"""Generate SDK resource classes and reference docs from spec/endpoints.json.

In an SDK repository (writes into the current repository):

    python3 tools/generate.py --lang node      # or python, php, go

In the yativo-sdks hub, with the SDK repositories checked out next to it
(node/, python/, php/, go/), this regenerates all of them and the guide data:

    python3 tools/generate.py

Writes, per language:
  node    src/resources.ts                 docs/REFERENCE.md
  python  src/yativo_fiat/resources.py     docs/REFERENCE.md
  php     src/Resources/*.php, src/ResourceMap.php, docs/REFERENCE.md
  go      resources.go                     docs/REFERENCE.md

Only the resource layer is generated. Clients, errors and webhook code are
written by hand in each SDK.
"""
import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / "spec" / "endpoints.json").read_text())
LANG_DIRS = {"node": "node", "python": "python", "php": "php", "go": "go"}
RESOURCES = SPEC["resources"]
HEADER = "Generated by tools/generate.py from spec/endpoints.json. Do not edit by hand."

# Typed results for the objects integrators branch on most (Node only; the
# other SDKs return dicts/arrays/maps with the same keys).
TS_TYPES = {
    ("deposits", "create"): "DepositCreated",
    ("deposits", "list"): "Deposit",
    ("deposits", "retrieve"): "Deposit",
    ("cardCheckout", "createOrder"): "CardCheckoutOrder",
    ("cardCheckout", "listOrders"): "CardCheckoutOrder",
    ("cardCheckout", "retrieveOrder"): "CardCheckoutOrder",
    ("cardCheckout", "account"): "CardCheckoutAccount",
    ("webhookEndpoints", "create"): "WebhookEndpoint",
    ("webhookEndpoints", "update"): "WebhookEndpoint",
    ("webhookEndpoints", "regenerateSecret"): "WebhookEndpoint",
}


def path_params(path):
    return re.findall(r"\{(\w+)\}", path)


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def pascal(name):
    return name[0].upper() + name[1:]


def write(root, rel, text):
    p = Path(root) / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    print("wrote", p.relative_to(Path.cwd()) if p.is_relative_to(Path.cwd()) else p)


# ---------------------------------------------------------------- Node / TS
def gen_node(root):
    out = [f"// {HEADER}", "", "import type { Requester, RequestOptions, Page, YativoObject, Query, Body } from './core.js';",
           "import type { Deposit, DepositCreated, CardCheckoutOrder, CardCheckoutAccount, WebhookEndpoint } from './types.js';", ""]
    for r in RESOURCES:
        cls = pascal(r["name"])
        out.append(f"/** {r['doc']} */")
        out.append(f"export class {cls} {{")
        out.append("  constructor(private readonly client: Requester) {}")
        for m in r["methods"]:
            pp = path_params(m["path"])
            kind = m["kind"]
            t = TS_TYPES.get((r["name"], m["name"]), "YativoObject")
            args = [f"{p}: string | number" for p in pp]
            if kind in ("query", "list"):
                args.append("query?: Query")
            if kind == "body":
                args.append("body?: Body")
            args.append("options?: RequestOptions")
            path_expr = "`" + re.sub(r"\{(\w+)\}", r"${encodeURIComponent(String(\1))}", m["path"]) + "`"
            req = {"query": "query", "list": "query", "body": "body"}.get(kind)
            extra = f", {{ ...options, {req} }}" if req else ", options"
            out.append("")
            out.append(f"  /** {m['doc']} `{m['http']} {m['path']}` */")
            if kind == "list":
                out.append(f"  {m['name']}({', '.join(args)}): Promise<Page<{t}>> {{")
                out.append(f"    return this.client.requestPage<{t}>('{m['http']}', {path_expr}{extra});")
            else:
                out.append(f"  {m['name']}({', '.join(args)}): Promise<{t}> {{")
                out.append(f"    return this.client.requestData<{t}>('{m['http']}', {path_expr}{extra});")
            out.append("  }")
        out.append("}")
        out.append("")
    out.append("export const resourceClasses = {")
    for r in RESOURCES:
        out.append(f"  {r['name']}: {pascal(r['name'])},")
    out.append("} as const;")
    out.append("")
    write(root, "src/resources.ts", "\n".join(out))


# ---------------------------------------------------------------- Python
def gen_python(root):
    out = [f'"""{HEADER}"""', "", "from typing import Any, Mapping, Optional, Union", "",
           "from ._core import Page, Requester, quote_path", "", ""]
    for r in RESOURCES:
        cls = pascal(r["name"])
        out.append(f"class {cls}:")
        out.append(f'    """{r["doc"]}"""')
        out.append("")
        out.append("    def __init__(self, client: Requester) -> None:")
        out.append("        self._client = client")
        for m in r["methods"]:
            pp = [snake(p) for p in path_params(m["path"])]
            kind = m["kind"]
            name = snake(m["name"])
            args = ["self"] + [f"{p}: Union[str, int]" for p in pp]
            if kind in ("query", "list", "body"):
                args.append("params: Optional[Mapping[str, Any]] = None")
            args.append("*")
            if kind in ("body", "delete"):
                args.append("idempotency_key: Optional[str] = None")
            args.append("timeout: Optional[float] = None")
            if kind in ("query", "list", "body"):
                args.append("**kwargs: Any")
            ret = "Page" if kind == "list" else "Any"
            path = m["path"]
            for orig in path_params(path):
                path = path.replace("{" + orig + "}", "{" + snake(orig) + "}")
            fmt = ", ".join(f"{p}=quote_path({p})" for p in pp)
            path_expr = f'"{path}".format({fmt})' if pp else f'"{path}"'
            out.append("")
            out.append(f"    def {name}({', '.join(args)}) -> {ret}:")
            out.append(f'        """{m["doc"]} ``{m["http"]} {m["path"]}``"""')
            call_kw = ["timeout=timeout"]
            if kind in ("body", "delete"):
                call_kw.append("idempotency_key=idempotency_key")
            if kind in ("query", "list"):
                call_kw.insert(0, "query={**(params or {}), **kwargs}")
            if kind == "body":
                call_kw.insert(0, "body={**(params or {}), **kwargs}")
            fn = "request_page" if kind == "list" else "request_data"
            out.append(f'        return self._client.{fn}("{m["http"]}", {path_expr}, {", ".join(call_kw)})')
        out.append("")
        out.append("")
    out.append("RESOURCE_CLASSES = {")
    for r in RESOURCES:
        out.append(f'    "{snake(r["name"])}": {pascal(r["name"])},')
    out.append("}")
    out.append("")
    write(root, "src/yativo_fiat/resources.py", "\n".join(out))


# ---------------------------------------------------------------- PHP
def gen_php(root):
    for r in RESOURCES:
        cls = pascal(r["name"])
        out = ["<?php", "", f"// {HEADER}", "", "declare(strict_types=1);", "", "namespace Yativo\\Fiat\\Resources;", "",
               "use Yativo\\Fiat\\Page;", "", f"/** {r['doc']} */", f"final class {cls} extends AbstractResource", "{"]
        first = True
        for m in r["methods"]:
            pp = path_params(m["path"])
            kind = m["kind"]
            args = [f"string|int ${p}" for p in pp]
            if kind in ("query", "list", "body"):
                args.append("array $params = []")
            args.append("array $options = []")
            path_expr = "'" + m["path"] + "'"
            if pp:
                repl = ", ".join(f"'{{{p}}}' => (string) ${p}" for p in pp)
                path_expr = f"$this->path({path_expr}, [{repl}])"
            ret = "Page" if kind == "list" else "mixed"
            if not first:
                out.append("")
            first = False
            out.append(f"    /** {m['doc']} `{m['http']} {m['path']}` */")
            out.append(f"    public function {m['name']}({', '.join(args)}): {ret}")
            out.append("    {")
            if kind == "list":
                out.append(f"        return $this->client->requestPage('{m['http']}', {path_expr}, ['query' => $params] + $options);")
            elif kind == "query":
                out.append(f"        return $this->client->requestData('{m['http']}', {path_expr}, ['query' => $params] + $options);")
            elif kind == "body":
                out.append(f"        return $this->client->requestData('{m['http']}', {path_expr}, ['body' => $params] + $options);")
            else:
                out.append(f"        return $this->client->requestData('{m['http']}', {path_expr}, $options);")
            out.append("    }")
        out.append("}")
        out.append("")
        write(root, f"src/Resources/{cls}.php", "\n".join(out))

    # Property docs for the client, so IDEs autocomplete $yativo->deposits->...
    props = "\n".join(f" * @property-read Resources\\{pascal(r['name'])} ${r['name']}" for r in RESOURCES)
    mapping = "\n".join(f"        '{r['name']}' => Resources\\{pascal(r['name'])}::class," for r in RESOURCES)
    write(root, "src/ResourceMap.php", f"""<?php

// {HEADER}

declare(strict_types=1);

namespace Yativo\\Fiat;

/**
{props}
 */
interface ResourceMap
{{
    public const CLASSES = [
{mapping}
    ];
}}
""")


# ---------------------------------------------------------------- Go
def gen_go(root):
    out = [f"// Code generated by tools/generate.py from spec/endpoints.json. DO NOT EDIT.", "", "package yativo", "",
           "import (", '\t"context"', '\t"net/url"', '\t"strings"', ")", "",
           "var _ = strings.NewReplacer // keep import when no path params", ""]
    fields = []
    for r in RESOURCES:
        svc = pascal(r["name"]) + "Service"
        fields.append((pascal(r["name"]), svc, r["doc"]))
        out.append(f"// {svc}: {r['doc']}")
        out.append(f"type {svc} struct{{ client *Client }}")
        out.append("")
        for m in r["methods"]:
            pp = path_params(m["path"])
            kind = m["kind"]
            args = ["ctx context.Context"] + [f"{p} string" for p in pp]
            if kind in ("query", "list"):
                args.append("query Query")
            if kind == "body":
                args.append("body any")
            args.append("opts ...RequestOption")
            if pp:
                pairs = ", ".join(f'"{{{p}}}", url.PathEscape({p})' for p in pp)
                path_expr = f'strings.NewReplacer({pairs}).Replace("{m["path"]}")'
            else:
                path_expr = f'"{m["path"]}"'
            q = "query" if kind in ("query", "list") else "nil"
            b = "body" if kind == "body" else "nil"
            out.append(f"// {pascal(m['name'])}: {m['doc']} {m['http']} {m['path']}")
            out.append(f"func (s *{svc}) {pascal(m['name'])}({', '.join(args)}) (*Response, error) {{")
            out.append(f'\treturn s.client.Do(ctx, "{m["http"]}", {path_expr}, {q}, {b}, opts...)')
            out.append("}")
            out.append("")
    out.append("// services holds every resource service. It is embedded in Client.")
    out.append("type services struct {")
    for f, svc, doc in fields:
        out.append(f"\t{f} *{svc}")
    out.append("}")
    out.append("")
    out.append("func newServices(c *Client) services {")
    out.append("\treturn services{")
    for f, svc, _ in fields:
        out.append(f"\t\t{f}: &{svc}{{client: c}},")
    out.append("\t}")
    out.append("}")
    out.append("")
    write(root, "resources.go", "\n".join(out))
    if shutil.which("gofmt"):
        subprocess.run(["gofmt", "-w", str(Path(root) / "resources.go")], check=True)


# ---------------------------------------------------------------- Endpoint table for the guide
def gen_guide_data(root):
    rows = []
    for r in RESOURCES:
        for m in r["methods"]:
            rows.append({
                "resource": r["name"], "method": m["name"], "http": m["http"], "path": m["path"],
                "kind": m["kind"], "doc": m["doc"],
                "py": f"{snake(r['name'])}.{snake(m['name'])}", "go": f"{pascal(r['name'])}.{pascal(m['name'])}",
            })
    write(root, "docs/assets/endpoints.js", "// " + HEADER + "\nwindow.YATIVO_ENDPOINTS = " + json.dumps(rows, indent=1) + ";\n")


# ---------------------------------------------------------------- per-language reference docs
def call_sig(lang, r, m):
    params = path_params(m["path"])
    kind = m["kind"]
    if lang == "node":
        args = params[:] + (["query?"] if kind in ("query", "list") else ["body?"] if kind == "body" else []) + ["options?"]
        return f"yativo.{r['name']}.{m['name']}({', '.join(args)})"
    if lang == "python":
        args = [snake(p) for p in params] + (["**filters"] if kind in ("query", "list") else ["**fields"] if kind == "body" else [])
        return f"yativo.{snake(r['name'])}.{snake(m['name'])}({', '.join(args)})"
    if lang == "php":
        args = ["$" + p for p in params] + (["array $filters = []"] if kind in ("query", "list") else ["array $body = []"] if kind == "body" else []) + ["array $options = []"]
        return f"$yativo->{r['name']}->{m['name']}({', '.join(args)})"
    args = ["ctx"] + params + (["query yativo.Query"] if kind in ("query", "list") else ["body any"] if kind == "body" else []) + ["opts ...yativo.RequestOption"]
    return f"client.{pascal(r['name'])}.{pascal(m['name'])}({', '.join(args)})"


RETURNS = {
    "node": ("the response `data`", "`Page` (`{ data, pagination }`)"),
    "python": ("the response `data` (dict or list)", "`Page` (iterate it; `.data`, `.pagination`, `.has_more`)"),
    "php": ("the response `data` (array)", "`Page` (`->data`, `->pagination`, `->hasMore()`)"),
    "go": ("`*yativo.Response` (call `.Decode(&v)`)", "`*yativo.Response` with `.Pagination`"),
}


def gen_reference(lang, root):
    total = sum(len(r["methods"]) for r in RESOURCES)
    one, many = RETURNS[lang]
    out = [
        "# API reference",
        "",
        f"<!-- {HEADER} -->",
        "",
        f"Every Yativo Fiat API endpoint this SDK wraps: {total} methods in {len(RESOURCES)} resources.",
        "Field names and response shapes are in the [Yativo API docs](https://docs.yativo.com).",
        "",
        f"- Single-object methods return {one}.",
        f"- List methods return {many}.",
        "- Write methods (`POST`, `PUT`, `PATCH`, `DELETE`) send an `Idempotency-Key`; pass your own to make retries safe.",
        "",
        "## Resources",
        "",
    ]
    for r in RESOURCES:
        name = snake(r["name"]) if lang == "python" else pascal(r["name"]) if lang == "go" else r["name"]
        out.append(f"- [`{name}`](#{name.lower()}): {r['doc']}")
    for r in RESOURCES:
        name = snake(r["name"]) if lang == "python" else pascal(r["name"]) if lang == "go" else r["name"]
        out += ["", f"## {name}", "", r["doc"], "", "| Method | Endpoint | What it does |", "|---|---|---|"]
        for m in r["methods"]:
            sig = call_sig(lang, r, m).replace("|", "\\|")
            out.append(f"| `{sig}` | `{m['http']} {m['path']}` | {m['doc']} |")
    out.append("")
    write(root, "docs/REFERENCE.md", "\n".join(out))


GENERATORS = {"node": gen_node, "python": gen_python, "php": gen_php, "go": gen_go}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lang", choices=sorted(GENERATORS) + ["all"], default="all")
    parser.add_argument("--root", help="Repository to write into (default: this repository, or the hub's checkouts for --lang all)")
    args = parser.parse_args()
    if args.lang == "all":
        for lang, fn in GENERATORS.items():
            target = ROOT / LANG_DIRS[lang]
            if not target.is_dir():
                print(f"skip {lang}: {target} is not checked out")
                continue
            fn(target)
            gen_reference(lang, target)
        if (ROOT / "docs").is_dir():
            gen_guide_data(ROOT)
        return
    target = Path(args.root) if args.root else ROOT
    GENERATORS[args.lang](target)
    gen_reference(args.lang, target)


if __name__ == "__main__":
    main()
